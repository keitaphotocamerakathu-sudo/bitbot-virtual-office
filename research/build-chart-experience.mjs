import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { gunzipSync } from 'node:zlib';
import { observeChart, retainCases, WINDOWS } from '../supabase/functions/bitbot-v10/master-chart-cases.mjs';

// Reproduce from the frozen Bitkub archive without a network request.
const archive = JSON.parse(gunzipSync(await readFile(new URL('./data-v31.json.gz', import.meta.url))));
const digest = createHash('sha256').update(JSON.stringify(archive.data)).digest('hex');
const original = JSON.parse(await readFile(new URL('../assets/master-research-v31.json', import.meta.url)));
assert.equal(digest, original.dataDigest);
assert.equal(digest, archive.dataDigest);
const pack = {
  source: 'BITKUB_CLOSED_OHLCV', dataDigest: digest, from: archive.start, to: archive.end,
  availableAt: Math.max(archive.end, Date.parse(archive.downloadedAt)), examined: 0, retained: 0, markets: {}
};
for (const [symbol, frames] of Object.entries(archive.data)) {
  const horizons = {};
  for (const [horizon, window] of Object.entries(WINDOWS)) {
    const { rows } = observeChart(frames[window.minutes], window, archive.end, archive.start);
    horizons[horizon] = retainCases(rows);
    pack.examined += rows.length;
    pack.retained += horizons[horizon].length;
  }
  pack.markets[symbol] = horizons;
}
const contents = '// Generated by research/build-chart-experience.mjs from the frozen Bitkub OHLCV archive.\n' +
  'export const CHART_ARCHIVE = ' + JSON.stringify(pack) + ';\n';
const target = new URL('../supabase/functions/bitbot-v10/master-chart-archive.mjs', import.meta.url);
if (process.argv.includes('--write')) await writeFile(target, contents);
else assert.equal(await readFile(target, 'utf8'), contents, 'Chart experience does not match archived prices');
console.log(JSON.stringify({ examined: pack.examined, retained: pack.retained, symbols: Object.keys(pack.markets), digest }));
